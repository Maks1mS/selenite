package storage

import (
	"fmt"
	"sort"
	"strings"
)

const marker = "# Generated by selenite-controller. Do not edit."

// UnitName returns the systemd mount unit name.
func UnitName(target string) string {
	parts := strings.Split(strings.Trim(target, "/"), "/")
	for i, p := range parts {
		parts[i] = strings.ReplaceAll(p, "-", `\x2d`)
	}
	return strings.Join(parts, "-") + ".mount"
}

func UnitContent(m Mount) string {
	mountType := m.Type
	if mountType == "disk" {
		mountType = m.Fs
	}
	var b strings.Builder
	b.WriteString(marker + "\n")
	b.WriteString("[Unit]\n")
	fmt.Fprintf(&b, "Description=Selenite storage mount %s at %s\n", m.Source, m.Target)
	b.WriteString("After=network-online.target\n")
	b.WriteString("Wants=network-online.target\n")
	b.WriteString("\n[Mount]\n")
	fmt.Fprintf(&b, "What=%s\n", m.Source)
	fmt.Fprintf(&b, "Where=%s\n", m.Target)
	fmt.Fprintf(&b, "Type=%s\n", mountType)
	if m.Options != "" {
		fmt.Fprintf(&b, "Options=%s\n", m.Options)
	}
	b.WriteString("\n[Install]\n")
	b.WriteString("WantedBy=remote-fs.target\n")
	return b.String()
}

// GateDropinContent renders the podman-restart.service drop-in gating
// container start on mount readiness. The gate script receives the sorted
// targets as arguments.
func GateDropinContent(mounts []Mount, gateScript string) string {
	targets := make([]string, 0, len(mounts))
	for _, m := range mounts {
		targets = append(targets, m.Target)
	}
	sort.Strings(targets)

	var b strings.Builder
	b.WriteString(marker + "\n")
	b.WriteString("[Service]\n")
	fmt.Fprintf(&b, "ExecStartPre=%s %s\n", gateScript, strings.Join(targets, " "))
	b.WriteString("Restart=on-failure\n")
	b.WriteString("RestartSec=60s\n")
	return b.String()
}
